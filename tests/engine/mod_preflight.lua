package.path='./?.lua;'..package.path
love=require('tests.love_stub')
local P=require('src.mods.ModPreflight')
local Manifest=require('src.mods.Manifest')
local count=0;local function check(v,m)assert(v,m);count=count+1 end
local function manifest(id,extra)
  local raw={id=id,name=id,version='1.0.0',api=2,entry='main.lua',games={'red','gold'}}
  for k,v in pairs(extra or {}) do raw[k]=v end
  return Manifest.validate(raw,'mods/'..id)
end
local function file(path,bytes)love.filesystem.write(path,bytes)end
file('mods/first/main.lua','_G.PREFLIGHT_EXECUTED=true; return {}')
file('mods/second/main.lua','return {}')
local first,second=manifest('first'),manifest('second')
local r=P.inspect({first,second},{},'red',love.filesystem)
check(#r.errors==0 and #r.checked==2 and not _G.PREFLIGHT_EXECUTED,'static inspection compiles trusted source without executing mod initialization')
first=manifest('first',{dependencies={{id='second',range='>=2.0.0'}}})
r=P.inspect({first,second},{},'red',love.filesystem)
check(#r.errors==1 and r.errors[1].message:find('>=2.0.0',1,true),'dependency version errors explain the required version')
r=P.inspect({first,second},{mods={second=false}},'red',love.filesystem)
check(r.errors[1].message:find('disabled',1,true),'disabled dependencies are caught before initialization')
first=manifest('first',{conflicts={'second'}})
r=P.inspect({first,second},{},'red',love.filesystem)
check(r.errors[1].message:find('Conflicts',1,true),'enabled mod conflicts block preflight')
file('mods/second/broken.lua','this cannot compile @')
r=P.inspect({first,second},{mods={first=false}},'gold',love.filesystem)
check(#r.errors==1 and r.errors[1].message:find('syntax',1,true),'syntax errors in secondary Lua modules are found before loading')
file('mods/second/broken.lua','return {}')
file('mods/second/bytecode.lua','\27Lua\0broken')
r=P.inspect({second},{},'red',love.filesystem)
check(r.warnings[1].message:find('bytecode',1,true),'binary bytecode is not executed or treated as portable source')
love.filesystem.remove('mods/second/bytecode.lua')
first=manifest('first',{dependencies={'second'}});second=manifest('second',{dependencies={'first'}})
r=P.inspect({first,second},{},'red',love.filesystem)
check(#r.errors==1 and r.errors[1].message:find('Circular',1,true),'dependency cycles are reported without running mods')
first=manifest('first',{games={'gold'}})
r=P.inspect({first},{},'red',love.filesystem)
check(#r.checked==0 and #r.skipped==1 and #r.warnings==1,'mods for another generation are skipped with an explicit explanation')
first=manifest('first',{game_version='>=99.0.0'})
r=P.inspect({first},{},'red',love.filesystem)
check(r.errors[1].message:find('Requires engine',1,true),'engine version requirements remain real constraints')
check(P.log(r):find('no mod code was executed',1,true) and P.log(r):find('not a gameplay test',1,true),'logs clearly distinguish static checks from runtime tests')
print('Mod preflight: '..count..' checks passed')
