-- The generated source remains authoritative despite coarse timestamps and
-- failed optional writes. Exercise the actual writer and require searcher.
package.path='./?.lua;./?/init.lua;'..package.path
local T=require('tests.harness')
local files,times={},{}
local failSidecars=false
local function read(path)return files[path]end
local function info(path)
 if files[path]then return{type='file',size=#files[path],modtime=times[path]}end
end
local function write(path,value)
 if failSidecars and not path:match('%.lua$')then return nil,'optional cache write denied'end
 files[path],times[path]=value,100;return true
end
love={filesystem={read=read,getInfo=info}}
package.loaded['src.import.CacheFs']={write=write,read=read}
local Cache=require('src.core.BytecodeCache')
local Writer=require('src.import.LuaWriter')
local key='data.generated.authority';local path='data/generated/authority.lua'
local function load()
 package.loaded[key]=nil
 return require(key)
end
local loaders=package.searchers or package.loaders
local sourceFallback=function(name)
 if name~=key then return nil end
 return files[path]and assert(loadstring(files[path],'@'..path))or nil
end
table.insert(loaders,1,sourceFallback)
T.eq(Cache.install(),true,'actual bytecode searcher installs')
Writer.write(path,{value='first'})
T.eq(load().value,'first','first generation loads')
local hits=Cache.hits or 0
T.eq(load().value,'first','unchanged same-second data loads from bytecode')
T.eq(Cache.hits,hits+1,'same-second cache can still accelerate requires')
-- A new source written in the same filesystem clock tick cannot inherit an
-- old compiled module if an optional sidecar write fails.
failSidecars=true
Writer.write(path,{value='second'})
T.eq(Cache.writeSidecar(path,files[path]),false,'a denied sidecar write is reported as optional failure')
T.eq(load().value,'second','failed same-second cache refresh falls back to new source')
T.eq(Cache.loadSidecar(path,read,info),nil,'stale bytes are not admitted at equal modtimes')
failSidecars=false
Writer.write(path,{value='third'})
T.eq(load().value,'third','successful retry updates compiled data')
files[path]='return {value="edited"}'
T.eq(load().value,'edited','source edits with preserved modtime invalidate compiled data')
files[path]=nil
T.eq(Cache.loadSidecar(path,read,info),nil,'an orphaned dump cannot replace a missing source')
T.eq(pcall(load),false,'missing authoritative source remains missing')
Writer.write(path,{value='restored'})
local function unreadable()error('injected read failure')end
local ok,result=pcall(Cache.loadSidecar,path,unreadable,info)
T.eq(ok,true,'optional cache read errors cannot abort source lookup')
T.eq(result,nil,'cache read error falls back to source')
local function unavailableInfo()error('injected stat failure')end
ok,result=pcall(Cache.loadSidecar,path,read,unavailableInfo)
T.eq(ok,true,'optional stat errors cannot abort source lookup')
T.eq(result,nil,'cache stat error falls back to source')
T.finish('generated bytecode cache keeps source authoritative')
